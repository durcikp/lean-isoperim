"""Consolidation of the auxiliary files of [DIR] §6 (Task 2).

This file was automatically generated by Claude.

Each main file `<M>.lean` of `Isoperim/DIR/6_Proof_Two_Point_Inequality/` has its auxiliary code
in `<M>_aux.lean`, continued in `<M>_aux_2.lean`, `<M>_aux_3.lean`, ... (a new part only when
the previous one would exceed `MAXLINES` lines); part `k` imports part `k-1`, the main file
imports the last part.

Usage (from the repository root):

* `python3 automation/cert/consolidate.py merge`
  One-time merge of the old per-topic aux modules (`<M>_aux_*.lean`, as listed in
  `Isoperim.lean`) into the consolidated parts; rewrites `Isoperim.lean` and all imports.
  Generated certificate code is wrapped to lines of at most 100 characters and enclosed in
  blocks `-- BEGIN GENERATED <name>` ... `-- END GENERATED <name>` (a block may be continued in
  the next part, between declarations).
* `python3 automation/cert/consolidate.py check`
  Reproducibility check: the generators `gen_*.py` write their output to `automation/cert/out/`
  (see `gen_common.DIR`); this compares the declarations of each `out/<name>.lean` (wrapped)
  with the declarations of the blocks `-- BEGIN GENERATED <name>` of the consolidated parts.
"""
