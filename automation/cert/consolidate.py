TITLES = {
    "6_1_Case_J": "[DIR] §6.1 Case J",
    "6_3_Case_LJQ": "[DIR] §6.3 Case LJQ",
    "6_4_Case_LJ": "[DIR] §6.4 Case LJ",
    "6_5_Case_QJQ": "[DIR] §6.5 Case QJQ",
    "6_6_Case_QJ": "[DIR] §6.6 Case QJ",
}

DECL = re.compile(r"^(/--|theorem |def |noncomputable |abbrev |set_option |lemma |@\[)")


def modname(path):
    """`Isoperim.DIR.«6_Proof_Two_Point_Inequality».«X»` -> X, else None."""
    m = re.fullmatch(re.escape(PKG) + r"\.«(.+)»", path)
    return m.group(1) if m else None


def parse(path):
    """Split a Lean module into (imports, module docstring, body)."""
    s = open(path).read()
    imports = re.findall(r"^public import (\S+)$", s, re.M)
    m = re.search(r"/-!\n(.*?)\n-/\n", s, re.S)
    doc = m.group(1) if m else ""
    i = s.index("@[expose] public section\n") + len("@[expose] public section\n")
    return imports, doc, s[i:]


def protect(line):
    """Glue `(by ...)` groups so that the wrapper does not break them."""
    return re.sub(r"\(by [^()]*\)", lambda m: m.group(0).replace(" ", "\x00"), line)


def wrap(line):
    """Wrap a generated line at spaces to at most `WIDTH` characters (continuation lines are
    indented by 4 more spaces)."""
    if len(line) <= WIDTH:
        return [line]
    ind = len(line) - len(line.lstrip(" "))
    toks = protect(line.strip()).split(" ")
    out, cur, cont = [], " " * ind, " " * (ind + 4)
    for t in toks:
        if cur.strip() and len(cur) + 1 + len(t) > WIDTH:
            out.append(cur.rstrip())
            cur = cont + t
        else:
            cur = (cur + " " + t) if cur.strip() else cur + t
    out.append(cur.rstrip())
    return [o.replace("\x00", " ") for o in out]


def wrap_doc(text):
    """Wrap the lines of a docstring text to at most `WIDTH` characters."""
    out = []
    for l in text.split("\n"):
        if len(l) <= WIDTH:
            out.append(l)
            continue
        ind = len(l) - len(l.lstrip(" "))
        sub = " " * (ind + 2 if l.lstrip().startswith(("* ", "- ")) else ind)
        out += textwrap.wrap(l, WIDTH, initial_indent="", subsequent_indent=sub,
                             break_long_words=False, break_on_hyphens=False)
    return "\n".join(out)


def doc_lines(doc):
    lines = [l for l in doc.split("\n")
             if l.strip() != "This file was automatically generated by Claude."]
    while lines and not lines[0].strip():
        lines.pop(0)
    return lines


def title_of(name, doc):
    lines = doc_lines(doc)
    return lines[0].lstrip("# ").strip() if lines else name


def section_doc(name, doc, level):
    """The docstring of an old module, as a section comment of the consolidated file."""
    lines = doc_lines(doc)
    rest = "\n".join(lines[1:]).strip("\n")
    t = title_of(name, doc)
    txt = f"/-! {level} {t}\n\n{rest}\n-/\n" if rest else f"/-! {level} {t} -/\n"
    return wrap_doc(txt)


def split_generated(body):
    """Split the body of a generated module into (prelude, declarations): the prelude is the
    `namespace`/`open` lines, each declaration a list of (wrapped) lines."""
    lines = body.strip("\n").split("\n")
    assert lines[-1] == "end Auto.DIR", lines[-1]
    lines = lines[:-1]
    i, prelude = 0, []
    while i < len(lines) and not DECL.match(lines[i]):
        if lines[i].strip():
            prelude.append(lines[i])
        i += 1
    decls, cur = [], []
    for j in range(i, len(lines)):
        l = lines[j]
        if not l.strip() and j + 1 < len(lines) and DECL.match(lines[j + 1]):
            if cur:
                decls.append(cur)
            cur = []
            continue
        cur.append(l)
    if cur:
        decls.append(cur)
    decls = [[w for l in d for w in wrap(l)] for d in decls]
    for d in decls:
        while d and not d[-1].strip():
            d.pop()
    return prelude, [d for d in decls if d]


def seg_open(o, doc, prelude, cont):
    head = (wrap_doc(f"/-! ### {title_of(o, doc)} (continued) -/") + "\n" if cont
            else section_doc(o, doc, "###"))
    return f"\n-- BEGIN GENERATED {o}\n" + head + "\n" + "\n".join(prelude) + "\n\n"


def seg_close(o):
    return f"end Auto.DIR\n-- END GENERATED {o}\n"


def nlines(txts):
    return sum(t.count("\n") for t in txts)


def pack(olds, data, budget):
    """Pack the old modules into parts of at most `budget` lines; returns a list of
    (texts, old modules contained). Generated modules are split between declarations."""
    parts, cur, mods = [], [], []

    def flush():
        nonlocal cur, mods
        if cur:
            parts.append((cur, mods))
        cur, mods = [], []
    for o in olds:
        _, doc, body = data[o]
        if o in HANDWRITTEN:
            t = "\n" + section_doc(o, doc, "##") + "\n" + body.strip("\n") + "\n"
            if cur and nlines(cur) + t.count("\n") > budget:
                flush()
            cur.append(t)
            mods.append(o)
            continue
        prelude, decls = split_generated(body)
        op, cl = seg_open(o, doc, prelude, False), seg_close(o)
        if cur and nlines(cur) + op.count("\n") + len(decls[0]) + 1 + cl.count("\n") > budget:
            flush()
        cur.append(op)
        mods.append(o)
        for d in decls:
            dt = "\n".join(d) + "\n\n"
            if nlines(cur) + dt.count("\n") + cl.count("\n") > budget:
                cur.append(cl)
                flush()
                cur.append(seg_open(o, doc, prelude, True))
                mods.append(o)
            cur.append(dt)
        cur[-1] = cur[-1].rstrip("\n") + "\n"
        cur.append(cl)
    flush()
    return parts


def part_name(M, k):
    return f"{M}_aux" if k == 0 else f"{M}_aux_{k + 1}"


def merge():
    iso = open("Isoperim.lean").read().split("\n")
    order = [modname(l.split()[-1]) for l in iso if l.startswith("public import")]
    newname, plan, data = {}, {}, {}
    for M in MAINS:
        olds = [m for m in order if m and (m == M + "_aux" or m.startswith(M + "_aux_"))]
        for o in olds:
            data[o] = parse(f"{ROOT}/{o}.lean")
        parts = pack(olds, data, MAXLINES - 40)
        plan[M] = [(part_name(M, k), txts, mods) for k, (txts, mods) in enumerate(parts)]
        for nm, _, mods in plan[M]:
            for o in mods:
                newname.setdefault(o, nm)   # first part containing (the start of) o
    # the last part containing o (for importers: all of o is available there)
    lastname = {}
    for M in MAINS:
        for nm, _, mods in plan[M]:
            for o in mods:
                lastname[o] = nm
    for M in MAINS:
        own = set()
        for k, (nm, txts, mods) in enumerate(plan[M]):
            imps = [f"{PKG}.«{part_name(M, k - 1)}»"] if k else []
            for o in dict.fromkeys(mods):
                for i in data[o][0]:
                    mo = modname(i)
                    if mo in lastname:
                        tgt = lastname[mo]
                        if tgt == nm or tgt in own:
                            continue
                        i = f"{PKG}.«{tgt}»"
                    if i not in imps:
                        imps.append(i)
            own.add(nm)
            doc = (f"Auxiliary file of `{M}.lean`, part {k + 1} of {len(plan[M])}"
                   + (f" (continued in `{plan[M][k + 1][0]}.lean`)" if k + 1 < len(plan[M])
                      else ""))
            if any(o not in HANDWRITTEN for o in mods):
                doc += (". Blocks between `-- BEGIN GENERATED` and `-- END GENERATED` are "
                        "generated by\nthe scripts `automation/cert/gen_*.py` (see "
                        "`automation/cert/consolidate.py`).")
            else:
                doc += "."
            title = f"{TITLES[M]}: auxiliary lemmas" + (f", part {k + 1}" if k else "")
            txt = HEADER.format(imports="\n".join(f"public import {i}" for i in imps),
                                title=title, doc=wrap_doc(doc))
            txt = (txt + "".join(txts)).rstrip("\n") + "\n"
            with open(f"{ROOT}/{nm}.lean", "w") as f:
                f.write(txt)
    news = {nm for M in MAINS for nm, _, _ in plan[M]}
    for o in data:
        if o not in news:
            os.remove(f"{ROOT}/{o}.lean")
    for dirpath, _, files in os.walk("Isoperim"):
        for fn in files:
            if fn.endswith(".lean"):
                p = os.path.join(dirpath, fn)
                s = open(p).read()
                if p.startswith(ROOT) and "_aux" in fn:
                    continue
                t = remap_imports(s, lastname)
                if t != s:
                    open(p, "w").write(t)
    out, done = [], set()
    for l in iso:
        mo = modname(l.split()[-1]) if l.startswith("public import") else None
        if mo in data:
            M = next(M for M in MAINS if mo == M + "_aux" or mo.startswith(M + "_aux_"))
            if M not in done:
                done.add(M)
                out += [f"public import {PKG}.«{nm}»" for nm, _, _ in plan[M]]
            continue
        out.append(l)
    open("Isoperim.lean", "w").write("\n".join(out))
    for M in MAINS:
        p = f"{ROOT}/{M}.lean"
        s = open(p).read().split("\n")
        parts = [f"public import {PKG}.«{nm}»" for nm, _, _ in plan[M]]
        s = [l for l in s if l not in parts[:-1]]
        if parts[-1] not in s:
            i = max(j for j, l in enumerate(s) if l.startswith("public import"))
            s.insert(i + 1, parts[-1])
        open(p, "w").write("\n".join(s))
    for M in MAINS:
        print(M, len(plan[M]), "parts")


def remap_imports(s, lastname):
    out, seen = [], set()
    for l in s.split("\n"):
        if l.startswith("public import "):
            mo = modname(l.split()[-1])
            if mo in lastname:
                l = f"public import {PKG}.«{lastname[mo]}»"
            if l in seen:
                continue
            seen.add(l)
        out.append(l)
    return "\n".join(out)


def check():
    """Compare regenerated output in `OUT` with the generated blocks of the parts."""
    blocks = {}
    files = [f for f in os.listdir(ROOT) if "_aux" in f]
    key = lambda f: (f.split("_aux")[0], int(re.sub(r"\D", "", f.split("_aux")[1]) or 1))
    for fn in sorted(files, key=key):
        s = open(f"{ROOT}/{fn}").read()
        for m in re.finditer(r"-- BEGIN GENERATED (\S+)\n(.*?)-- END GENERATED \1\n", s, re.S):
            blocks.setdefault(m.group(1), []).append(m.group(2))
    bad = 0
    for name, segs in sorted(blocks.items()):
        src = f"{OUT}/{name}.lean"
        if not os.path.exists(src):
            print("not regenerated:", name)
            continue
        decls = split_generated(parse(src)[2])[1]
        have = []
        for seg in segs:
            have += split_generated(seg[seg.index("\nnamespace ") + 1:])[1]
        if have != decls:
            bad += 1
            print("DIFFERS:", name)
    print("checked", len(blocks), "blocks,", bad, "differ")


if __name__ == "__main__":
    {"merge": merge, "check": check}[sys.argv[1]]()
